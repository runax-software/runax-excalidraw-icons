from urllib.parse import quote

from ..icon import Icon
from .pack import Pack
from .restrictions import Restrictions

README_COLUMNS = 6
README_SAMPLES = 24
PREVIEW_SIZE = 64


class ReadmeRenderer:
    """A pack's README.md: source, a preview grid of sample icons, license and sources.

    (Named renderer.py, not readme.py: GitHub shows any README.* file as the folder's readme.)
    """

    def __init__(self, pack: Pack, icons: list[Icon]):
        self.pack = pack
        self.icons = icons
        self.config = pack.config

    def render(self) -> str:
        samples = self._samples()
        return f"""# {self.config.title}

{len(self.icons)} icons from {self.config.source}, packaged as a Miro-style Excalidraw library:
each item is a 64px icon with an editable label below it, grouped together.

<table>
{self._grid(samples)}
</table>

{len(samples)} of {len(self.icons)} shown. Every icon is in [`src/`](src/).{self._changelog()}
{self._license()}{self._sources()}
## Use

Build with `uv run runax-icons build` from the repo root, then in Excalidraw:

1. Open `{self.pack.scene_path.name}` (or paste icons from it into your drawing), so the images are loaded.
2. Import `{self.pack.library_path.name}` from the library panel.

Excalidraw doesn't store images in library files, so library icons render only once the
drawing contains them. See the [main README](../README.md).

<!-- Generated by runax-icons build; edit pack.yml instead. -->
"""

    def _samples(self) -> list[tuple[str, Icon]]:
        """(label, icon) for the configured samples that exist, else the first icons."""
        by_label = {self.pack.label(icon): icon for icon in self.icons}
        chosen = [label for label in self.config.samples if label in by_label]
        return [(label, by_label[label]) for label in chosen or list(by_label)[:README_SAMPLES]]

    @staticmethod
    def _grid(samples: list[tuple[str, Icon]]) -> str:
        cells = [
            f'<td align="center" width="120"><img src="{quote(f"src/{icon.path}")}" {_preview_size(icon)}><br>'
            f"<sub>{label}</sub></td>"
            for label, icon in samples
        ]
        rows = [
            "<tr>" + "".join(cells[i : i + README_COLUMNS]) + "</tr>"
            for i in range(0, len(cells), README_COLUMNS)
        ]
        return "\n".join(rows)

    def _changelog(self) -> str:
        if not self.pack.changelog_path.exists():
            return ""
        return " Changes are in [`CHANGELOG.md`](CHANGELOG.md)."

    def _license(self) -> str:
        if not self.config.license:
            return ""

        forbidden = "".join(
            f"- `{operation}`: {reason}\n" for operation, reason in self.config.forbid.forbidden.items()
        )
        restrictions = f"\nThis pack forbids, and the build refuses:\n\n{forbidden}" if forbidden else ""
        return f"""
## License

{self.config.license.strip()}
{restrictions}"""

    def _sources(self) -> str:
        rows = [
            f"| `{entry.files}` | {entry.url} | {'; '.join(entry.notes())} |"
            for entry in self.config.imports
        ] + [
            f"| `{s.files}` | {s.url} | {'; '.join(filter(None, [s.note, _forbids(s.forbid)]))} |"
            for s in self.config.sources
        ]
        if not rows:
            return ""

        downloaded = (
            f"Imports last fetched {self.config.downloaded}. " if self.config.downloaded else ""
        )
        return f"""
## Sources

{downloaded}Paths are relative to [`src/`](src/). Imported files are refreshed by
`uv run runax-icons import {self.pack.name}`; the rest are kept by hand.

| Files | Source | Notes |
| ----- | ------ | ----- |
{chr(10).join(rows)}
"""


def _preview_size(icon: Icon) -> str:
    """width and height attributes fitting the icon in PREVIEW_SIZE without distorting it
    (vendor terms forbid changing an icon's shape, and a forced square would)."""
    width = round(PREVIEW_SIZE * min(1, icon.aspect))
    height = round(PREVIEW_SIZE * min(1, 1 / icon.aspect))
    return f'width="{width}" height="{height}"'


def _forbids(forbid: Restrictions) -> str:
    return "forbids " + ", ".join(f"`{op}`" for op in forbid.forbidden) if forbid else ""
