from urllib.parse import quote

README_COLUMNS = 6
README_SAMPLES = 24


class ReadmeRenderer:
    """A pack's README.md: source, icon count and a preview grid of sample icons."""

    def render(self, pack, icons):
        by_label = {icon.label(pack.labels): icon.path for icon in icons}
        missing = [label for label in pack.samples if label not in by_label]

        if missing:
            print(f"[{pack.name}] README samples not found: {', '.join(missing)}")

        samples = [label for label in pack.samples if label in by_label] or list(
            by_label
        )[:README_SAMPLES]

        cells = [
            f'<td align="center" width="120"><img src="{quote(f"src/{by_label[label]}")}" width="64" height="64"><br>'
            f"<sub>{label}</sub></td>"
            for label in samples
        ]

        rows = [
            "<tr>" + "".join(cells[i : i + README_COLUMNS]) + "</tr>"
            for i in range(0, len(cells), README_COLUMNS)
        ]

        return f"""# {pack.title}

{len(icons)} icons from {pack.source}, packaged as a Miro-style Excalidraw library:
each item is a 64px icon with an editable label below it, grouped together.

<table>
{chr(10).join(rows)}
</table>

{len(samples)} of {len(icons)} shown. Every icon is in [`src/`](src/).
{self._sources(pack)}
## Use

Build with `uv run build.py` from the repo root, then in Excalidraw:

1. Open `{pack.scene_path.name}` (or paste icons from it into your drawing), so the images are loaded.
2. Import `{pack.library_path.name}` from the library panel.

Excalidraw doesn't store images in library files, so library icons render only once the
drawing contains them. See the [main README](../README.md).

<!-- Generated by build.py; edit pack.yml instead. -->
"""

    @staticmethod
    def _sources(pack):
        rows = [f"| `{files}` | {url} | {notes} |" for files, url, notes in pack.source_rows()]
        if not rows:
            return ""

        downloaded = f"Imports last fetched {pack.downloaded}. " if pack.downloaded else ""

        return f"""
## Sources

{downloaded}Paths are relative to [`src/`](src/). Imported files are refreshed by
`uv run build.py --import {pack.name}`; the rest are kept by hand.

| Files | Source | Notes |
| ----- | ------ | ----- |
{chr(10).join(rows)}
"""
